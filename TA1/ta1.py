import agentpy as ap
import random
import matplotlib.pyplot as plt
import numpy as np

# -------- Get user input from console --------
num_agents = int(input("Enter number of agents: "))
grid_size = int(input("Enter grid size (e.g., 10 for 10x10): "))
num_steps = int(input("Enter number of steps: "))

# -------- Agent Definition -----------
class CustomWalker(ap.Agent):
    def setup(self):
        self.position = (0, 0)
        self.path = []

    def step(self):
        # Record current position before moving
        self.path.append(self.position)

        # Movement Rules
        if self.model.p.bias:
            # Preferred direction: biased towards +x (right) and +y (up)
            # Weights: Right (40%), Up (40%), Left (10%), Down (10%)
            direction = random.choices(
                [(1,0), (0,1), (-1,0), (0,-1)],
                weights=[0.4, 0.4, 0.1, 0.1],
                k=1
            )[0]
        else:
            # Unbiased standard random walk
            direction = random.choice([(1,0), (-1,0), (0,1), (0,-1)])

        x, y = self.position
        # Keep agents inside grid
        x = max(0, min(self.model.p.grid_size[0]-1, x + direction[0]))
        y = max(0, min(self.model.p.grid_size[1]-1, y + direction[1]))
        self.position = (x, y)

    def record_final_path(self):
        # Record the very last position
        self.path.append(self.position)

# -------- Model Definition -----------
class RandomWalkModel(ap.Model):
    def setup(self):
        # Create agents
        self.agents = ap.AgentList(self, self.p.agents, CustomWalker)

        # Initialize random positions
        for agent in self.agents:
            agent.position = (random.randint(0, self.p.grid_size[0]-1),
                              random.randint(0, self.p.grid_size[1]-1))
            agent.path = [agent.position]

        # Create grid
        self.grid = ap.Grid(self, self.p.grid_size, torus=False)
        self.grid.add_agents(self.agents)

    def step(self):
        self.agents.step()

    def end(self):
        for agent in self.agents:
            agent.record_final_path()

# -------- Run Scenario A: Standard Random Walk -----------
params_a = {
    'agents': num_agents,
    'grid_size': (grid_size, grid_size),
    'steps': num_steps,
    'bias': False
}
model_a = RandomWalkModel(params_a)
model_a.run()

# -------- Run Scenario B: Biased Walk (Preferred Direction) -----------
params_b = {
    'agents': num_agents,
    'grid_size': (grid_size, grid_size),
    'steps': num_steps,
    'bias': True
}
model_b = RandomWalkModel(params_b)
model_b.run()

# -------- Extract Results for Analysis & Visualization --------
def analyze_model_results(model):
    final_positions = np.array([agent.position for agent in model.agents])
    x_final = final_positions[:, 0]
    y_final = final_positions[:, 1]

    mean_pos = np.mean(final_positions, axis=0)
    var_pos = np.var(final_positions, axis=0)
    return final_positions, x_final, y_final, mean_pos, var_pos

pos_a, x_a, y_a, mean_a, var_a = analyze_model_results(model_a)
pos_b, x_b, y_b, mean_b, var_b = analyze_model_results(model_b)

print("=== SCENARIO A: Standard Random Walk ===")
print(f"Mean final position: {mean_a}")
print(f"Variance of final position: {var_a}\n")

print("=== SCENARIO B: Biased Random Walk (Preferred Up/Right) ===")
print(f"Mean final position: {mean_b}")
print(f"Variance of final position: {var_b}\n")

# -------- Plot and Compare Both Scenarios -----------
fig, axes = plt.subplots(2, 2, figsize=(14, 12))

# Helper to plot paths
def plot_paths(ax, model, title):
    ax.set_title(title)
    ax.set_xlim(-0.5, grid_size - 0.5)
    ax.set_ylim(-0.5, grid_size - 0.5)
    ax.set_xticks(range(grid_size))
    ax.set_yticks(range(grid_size))
    ax.grid(True, linestyle='--', alpha=0.5)

    # Plot paths for each agent
    for agent in model.agents:
        xs = [p[0] for p in agent.path]
        ys = [p[1] for p in agent.path]
        ax.plot(xs, ys, alpha=0.3, linewidth=1.5)

    # Plot final positions
    xs_final = [agent.position[0] for agent in model.agents]
    ys_final = [agent.position[1] for agent in model.agents]
    ax.scatter(xs_final, ys_final, color='red', zorder=5, s=50, label='Final Pos')
    ax.legend()

# Helper to plot final position heatmap/distribution
def plot_heatmap(ax, x_pos, y_pos, title):
    ax.set_title(title)
    counts, xedges, yedges = np.histogram2d(x_pos, y_pos, bins=np.arange(grid_size+1))
    im = ax.imshow(counts.T, origin='lower', cmap='YlOrRd', extent=[0, grid_size, 0, grid_size])
    ax.set_xticks(range(grid_size))
    ax.set_yticks(range(grid_size))
    ax.grid(True, linestyle='--', alpha=0.5)
    fig.colorbar(im, ax=ax, label='Agent Count')

# Plot Scenario A
plot_paths(axes[0, 0], model_a, "Scenario A: Paths (Standard)")
plot_heatmap(axes[0, 1], x_a, y_a, "Scenario A: Final Heatmap")

# Plot Scenario B
plot_paths(axes[1, 0], model_b, "Scenario B: Paths (Biased Up-Right)")
plot_heatmap(axes[1, 1], x_b, y_b, "Scenario B: Final Heatmap")

plt.tight_layout()
plt.show()