import random

class VacuumAgent:
    def __init__(self, start_location='A'):
        self.location = start_location

    def display_grid(self, environment):
        grid = []
        for room in ['A', 'B', 'C']:
            if room == self.location:
                grid.append(f"[{room}-Agent]")
            else:
                grid.append(f"[{room}-{environment[room]}]")
        print(" ".join(grid))

    def perceive_and_act(self, environment):
        if environment[self.location].lower() == 'dirty':
            environment[self.location] = 'Clean'
            print(f"Room {self.location} has been cleaned.")
            self.display_grid(environment)
        else:
            if all(state.lower() == 'clean' for state in environment.values()):
                print("All rooms are clean. Agent is idle.")
                self.display_grid(environment)
            else:
                other_rooms = [r for r in ['A', 'B', 'C'] if r != self.location]
                self.location = random.choice(other_rooms)
                print(f"Moving to room {self.location}")
                self.display_grid(environment)


def main():
    # Task 1: Set Up Environment for Rooms A, B, and C
    environment = {}
    environment['A'] = input("Is room A Dirty or Clean? ").strip().capitalize()
    environment['B'] = input("Is room B Dirty or Clean? ").strip().capitalize()
    environment['C'] = input("Is room C Dirty or Clean? ").strip().capitalize()

    # Task 2: Implement the Rule-Based Agent
    agent = VacuumAgent(start_location='A')

    # Task 3: Run the Simulation
    steps = int(input("How many steps should the agent run? "))

    for step in range(1, steps + 1):
        print(f"\nStep {step}:")
        agent.display_grid(environment)
        agent.perceive_and_act(environment)

    print("\nSimulation completed yippie")


if __name__ == "__main__":
    main()