# Case Study 1: Disaster Response DSS

import json

case_base = [
    {
        "case_id": "C001",
        "problem": {
            "disaster_type": "Typhoon",
            "location": "Urban",
            "severity": "High",
            "population_affected": 50000
        },
        "solution": {
            "evacuation_strategy": "Mandatory vertical and horizontal evacuation",
            "resource_allocation": "500 relief packs, 20 rescue boats",
            "shelter_capacity": 10000
        }
    },
    {
        "case_id": "C002",
        "problem": {
            "disaster_type": "Flood",
            "location": "Rural",
            "severity": "Moderate",
            "population_affected": 15000
        },
        "solution": {
            "evacuation_strategy": "Partial evacuation of low-lying riverside areas",
            "resource_allocation": "150 relief packs, 8 rescue boats",
            "shelter_capacity": 3000
        }
    },
    {
        "case_id": "C003",
        "problem": {
            "disaster_type": "Earthquake",
            "location": "Urban",
            "severity": "Critical",
            "population_affected": 80000
        },
        "solution": {
            "evacuation_strategy": "Immediate open-space assembly and structural inspection",
            "resource_allocation": "800 medical kits, heavy search-and-rescue equipment",
            "shelter_capacity": 20000
        }
    }
]

print("="*60)
print(" DISASTER RESPONSE DECISION SUPPORT SYSTEM (DSS)")
print("="*60)
print("Please enter the parameters for the new disaster event:\n")

disaster_type = input("Enter Disaster Type (e.g., Typhoon, Flood, Earthquake): ").strip().capitalize()
location = input("Enter Location Type (e.g., Urban, Rural): ").strip().capitalize()
severity = input("Enter Severity Level (e.g., Moderate, High, Critical): ").strip().capitalize()

while True:
    try:
        population_affected = int(input("Enter Population Affected (e.g., 65000): "))
        break
    except ValueError:
        print("❌ Invalid input. Please enter a valid integer for the population.")

new_problem = {
    "disaster_type": disaster_type,
    "location": location,
    "severity": severity,
    "population_affected": population_affected
}

print("\n" + "="*60)
print(" INPUT: NEW PROBLEM DESCRIPTION")
print("="*60)
print(json.dumps(new_problem, indent=4))

def retrieve_similar_case(new_prob, cases):
    best_match = None
    highest_score = -1

    for case in cases:
        score = 0
        if case["problem"]["disaster_type"] == new_prob["disaster_type"]:
            score += 50
        if case["problem"]["location"] == new_prob["location"]:
            score += 30
        if case["problem"]["severity"] == new_prob["severity"]:
            score += 20

        if score > highest_score:
            highest_score = score
            best_match = case

    return best_match, highest_score

retrieved_case, similarity_score = retrieve_similar_case(new_problem, case_base)

print("\n" + "="*60)
print(" PROCESS: RETRIEVED SIMILAR CASE")
print("="*60)
print(f"Similarity Score: {similarity_score}%")
print(json.dumps(retrieved_case, indent=4))

if retrieved_case["problem"]["population_affected"] > 0:
    scale_factor = new_problem["population_affected"] / retrieved_case["problem"]["population_affected"]
else:
    scale_factor = 1.0

adapted_solution = {
    "evacuation_strategy": retrieved_case["solution"]["evacuation_strategy"] + " (Adjusted for population scale)",
    "resource_allocation": f"Scaled by factor {scale_factor:.2f}: Adjusted relief packs and units",
    "shelter_capacity": int(retrieved_case["solution"]["shelter_capacity"] * scale_factor)
}

print("\n" + "="*60)
print(" PROCESS: ADAPTED FINAL SOLUTION")
print("="*60)
print(json.dumps(adapted_solution, indent=4))

new_case_entry = {
    "case_id": f"C00{len(case_base) + 1}",
    "problem": new_problem,
    "solution": adapted_solution
}

case_base.append(new_case_entry)

print("\n" + "="*60)
print(" OUTPUT: RETAIN & UPDATED CASE BASE")
print("="*60)
print("✔ New case successfully saved to the Case Base!\n")
print(json.dumps(case_base, indent=4))