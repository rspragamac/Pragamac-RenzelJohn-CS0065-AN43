print("=== LABORATORY TASK: RBR & CBR ===")
facts = {
    "temperature": 34,         # Category: Temperature
    "is_raining": True,          # Category: Status / Weather
    "humidity": 90,            # Category: Environment
    "power_outage": False,     # Category: Status
    "motion_detected": True    # Category: Presence / Actions
}

print("Knowledge Base (Facts):")
for key, value in facts.items():
    print(f"  - {key}: {value}")

def rule_hot(facts):
    if facts.get("temperature", 0) > 30:
        return "Turn on the aircon"
    return None

def rule_rain(facts):
    if facts.get("is_raining", False):
        return "Bring umbrella"
    return None

def rule_security(facts):
    if facts.get("motion_detected", False) and not facts.get("power_outage", False):
        return "Activate security camera alert"
    return None

rules = [rule_hot, rule_rain, rule_security]

def inference_engine(facts, rules):
    actions = []
    for rule in rules:
        action = rule(facts)
        if action:
            actions.append(action)
    return actions

print("Rule-Based Reasoning")
print("Actions:")
inferred_actions = inference_engine(facts, rules)
for action in inferred_actions:
    print(f"- {action}")

case_base = [
    {
        "problem": {"won_t_turn_on": True, "noise": False, "indicator_light": False},
        "solution": "Check power cable and wall outlet connection."
    },
    {
        "problem": {"won_t_turn_on": False, "noise": True, "indicator_light": True},
        "solution": "Clean air filter and check for fan blade obstruction."
    },
    {
        "problem": {"won_t_turn_on": True, "noise": True, "indicator_light": False},
        "solution": "Reset circuit breaker and inspect fuse box."
    }
]

fn_similarity = lambda p1, p2: sum(1 for k, v in p1.items() if k in p2 and p2[k] == v)

def retrieve_most_similar(new_problem, case_base):
    best_match = None
    max_score = -1
    for case in case_base:
        score = fn_similarity(new_problem, case["problem"])
        if score > max_score:
            max_score = score
            best_match = case
    return best_match

new_problem = {"won_t_turn_on": True, "noise": False, "indicator_light": False}
print(f"New Problem Input: {new_problem}")

retrieved_case = retrieve_most_similar(new_problem, case_base)
print(f"Retrieved Similar Solution: {retrieved_case['solution']}")

user_feedback = input("\n[Revise] Do you want to adjust this solution? (Type a new solution or press Enter to keep): ").strip()

if user_feedback:
    final_solution = user_feedback
    print(f"-> Solution revised to: {final_solution}")
else:
    final_solution = retrieved_case["solution"]
    print("-> Solution kept unchanged.")

new_case = {
    "problem": new_problem,
    "solution": final_solution
}
case_base.append(new_case)
print(f"\n[Retain] New case successfully added! Total cases in case base: {len(case_base)}")